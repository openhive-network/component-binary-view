/// <reference types="node" />

import { Eta } from "eta";
import packageJson from './package.json';
import url from 'node:url';
import path from 'node:path';
import fs from 'node:fs';
import type { TBinaryViewEmits, TBinaryViewPropKeys } from './src/components/BinaryView/types';

if (process.argv.length !== 4)
  throw new Error("Usage: npx tsx render-package.ts <inputDir> <outputDir>");

const inputDir = process.argv[2];
const outputDir = process.argv[3];

console.log(`Rendering ${inputDir} to ${outputDir}`);

const __dirname = url.fileURLToPath(new URL('.', import.meta.url));

const eta = new Eta({ views: path.join(__dirname, inputDir) });

const events: Array<{ name: TBinaryViewEmits; description: string; example: string }> = [
  {
    name: 'copy',
    description: 'Emitted when the user copies the binary or hexadecimal data to the clipboard. May be used to display a toast message.',
    example: `@copy="console.log('Copied!')"`
  }
];

const properties: Array<{ name: TBinaryViewPropKeys; type: string; default: string; description: string; }> = [
  {
    name: 'data',
    type: 'object',
    default: '',
    description: 'Required property that contains the binary data to display generated by wax.'
  },
  {
    name: 'rootnode',
    type: 'string',
    default: 'transaction',
    description: 'When non-empty value provided, the virtual root node will be named as the value of this property. This will allow to select the entire binary data as a single named node.'
  },
  {
    name: 'dark',
    type: 'boolean',
    default: 'false',
    description: 'Whether to use the dark theme.'
  },
  {
    name: 'rowbytes',
    type: 'number',
    default: '16',
    description: 'The number of bytes to display per row.'
  },
  {
    name: 'uppercase',
    type: 'boolean',
    default: 'false',
    description: 'Should the hexadecimal data be displayed in uppercase'
  }
];

const it = {
  name: packageJson.name,
  description: packageJson.description,
  version: packageJson.version,
  author: packageJson.author,
  license: packageJson.license,
  dependencies: packageJson.dependencies,
  events,
  properties
}

const packageStr = eta.render("./package.template.json", it);
const readmeStr = eta.render("./README.template.md", it);
if (fs.existsSync(path.join(__dirname, inputDir, "binary-view.template.d.ts")))
  fs.writeFileSync(path.join(__dirname, outputDir, "binary-view.d.ts"), eta.render("./binary-view.template.d.ts", it), { encoding: 'utf8' });

fs.writeFileSync(path.join(__dirname, outputDir, "package.json"), packageStr, { encoding: 'utf8' });
fs.writeFileSync(path.join(__dirname, outputDir, "README.md"), readmeStr, { encoding: 'utf8' });
